"""Generate APFS lookup tables from https://www.unicode.org/Public/zipped/9.0.0/UCD.zip."""
import sys
from zipfile import ZipFile

with ZipFile(sys.argv[1]) as archive:
    assert "Version 9.0.0" in archive.read("ReadMe.txt").decode("utf-8")
    ucd = archive.read("UnicodeData.txt").decode("utf-8").splitlines()
    folding = archive.read("CaseFolding.txt").decode("utf-8").splitlines()

assigned = []
decompositions = {}
combining = {}
first = None
for line in ucd:
    fields = line.split(";")
    point, name = int(fields[0], 16), fields[1]
    if name.endswith(", First>"):
        first = point
        continue
    start, first = (first if first is not None else point), None
    if assigned and assigned[-1][1] + 1 == start:
        assigned[-1][1] = point
    else:
        assigned.append([start, point])
    if int(fields[3]):
        combining[point] = int(fields[3])
    if fields[5] and not fields[5].startswith("<"):
        decompositions[point] = [int(p, 16) for p in fields[5].split()]

folds = {}
for line in folding:
    line = line.split("#", 1)[0].strip()
    if line:
        point, status, mapping, _ = line.split(";")
        if status.strip() in ("C", "F"):
            folds[int(point, 16)] = [int(p, 16) for p in mapping.split()]

def table(kind, name, rows):
    print()
    print(f"constexpr {kind} {name}[] = {{")
    for row in rows:
        print("    {" + ",".join(f"0x{v:x}" for v in row) + "},")
    print("};")

def mappings(name, data):
    table("Mapping", name, ([key, *values] for key, values in sorted(data.items())))

print("""// Generated by tests/generate-apfs-unicode.py from Unicode 9.0.0.
// Copyright (c) Unicode, Inc. See licenses/Unicode-DFS.txt.
""")
table("CodeRange", "assigned", assigned)
table("Combining", "combining", sorted(combining.items()))
mappings("decomposition", decompositions)
mappings("caseFold", folds)
