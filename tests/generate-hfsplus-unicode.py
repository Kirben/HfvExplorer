from pathlib import Path
import unicodedata as u
db=u.ucd_3_2_0
decomp=[];ccc=[];fold=[]
for cp in range(0x110000):
 ch=chr(cp)
 if db.category(ch)=='Cn':continue
 d=db.decomposition(ch)
 if d and not d.startswith('<') and not (0x2000<=cp<=0x2fff or 0xf900<=cp<=0xfaff or 0x2f800<=cp<=0x2faff):
  seq=[int(x,16) for x in d.split()]
  if len(seq)<=2:decomp.append((cp,seq[0],seq[1] if len(seq)>1 else 0))
 cc=db.combining(ch)
 if cc:ccc.append((cp,cc))
root=Path(__file__).resolve().parent.parent
for line in (root/'tests/hfsplus-name-folds.txt').read_text().splitlines():
 if line and not line.startswith('#'):fold.append(tuple(int(x,16) for x in line.split()))
p=root/'src/HfsPlusUnicodeData.h'
p.write_text('// SPDX-License-Identifier: GPL-2.0-or-later\n// Generated by tests/generate-hfsplus-unicode.py using Python Unicode 3.2 data.\n'+
 'static const uint32_t decompositions[][3]={\n'+''.join('{0x%x,0x%x,0x%x},\n'%x for x in decomp)+'};\n'+
 'static const uint32_t combiningClasses[][2]={\n'+''.join('{0x%x,%d},\n'%x for x in ccc)+'};\n'+
 'static const uint16_t folds[][2]={\n'+''.join('{0x%x,0x%x},\n'%x for x in fold)+'};\n',encoding='ascii')
